-- 4. 슬롯은 스케줄러가 만든다
--    스케줄러는 "서버가 켜질 때" 그 시점에 DB에 있는 어트랙션의 슬롯을 만든다.
--    서버가 이미 켜진 상태에서 이 파일을 실행했다면, 서버를 재시작해야 바로 슬롯이 생긴다.
--    (재시작하지 않으면 다음 날 00:05에 생긴다)
--
--    재시작 후 확인: 어트랙션마다 슬롯이 0보다 많이 나와야 한다.
--    (오늘은 지금 이후 시각만 만들기 때문에 정확한 개수는 실행 시각마다 다르다)
SELECT a.name, COUNT(s.id) AS slot_count
FROM attractions a
         LEFT JOIN attraction_slots s ON s.attraction_id = a.id
WHERE a.deleted_at IS NULL
  AND a.name IN ('범퍼카', '우주전투기', '아마존 익스프레스', '모니모 러쉬', '썬더폴스',
                 '콜럼버스 대탐험', '더블 락스핀', '렛츠 트위스트', '롤링 엑스 트레인', '허리케인')
GROUP BY a.name
ORDER BY a.name;